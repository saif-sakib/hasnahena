// WO-52 — what a notification actually *says*.
//
// The integration suites assert a notification row exists;
// failure_injection_integration_test.go counts them. None of them reads a
// `message`. That is how every amount in this system came to be rendered
// "BDT 50000.00" — two paisa digits in a ledger that has no paisa — for as long
// as it did.
//
// This suite reads the strings. The assertions that matter are in
// checkMoneyMessage: the amount appears exactly once, as whole taka, equal to
// the int64 that went in, with no decimal point anywhere in the body. Reintroduce
// a `%.2f` in messages.go and every money row here fails.
//
// TestEveryBuilderIsTested is the census. It parses messages.go and fails when
// an exported builder has no row in the table below — the discipline that caught
// LEDGER-05 on the balance writers, applied to the layer with the same shape.

// ---------------------------------------------------------------------------
// FormatTaka
// ---------------------------------------------------------------------------

func TestFormatTaka(t *testing.T) {
	cases := []struct {
		amount int64
		want   string
	}{
		{0, "0"},
		{1, "1"},
		{999, "999"},
		{1000, "1,000"},
		{50000, "50,000"},
		{100000, "100,000"},
		{1234567, "1,234,567"},
		{-5000, "-5,000"},
		// int64 boundaries. A member will never hold this, but a corrupted or
		// hostile value must still render as a number rather than panic or
		// silently lose precision the way float64 would above 2^53.
		{9223372036854775807, "9,223,372,036,854,775,807"},
		{-9223372036854775808, "-9,223,372,036,854,775,808"},
	}
	for _, c := range cases {
		if got := FormatTaka(c.amount); got != c.want {
			t.Errorf("FormatTaka(%d) = %q, want %q", c.amount, got, c.want)
		}
	}
}

// TestFormatTakaMatchesTheWebApp pins the grouping against the values
// apps/web/lib/utils.ts produces with Intl.NumberFormat('en-BD'). If someone
// switches this package to the lakh-crore grouping used by the PDF renderer,
// the app and its own notifications start disagreeing, and this says so.
func TestFormatTakaMatchesTheWebApp(t *testing.T) {
	// Generated by: new Intl.NumberFormat('en-BD', { style: 'currency',
	// currency: 'BDT', minimumFractionDigits: 0, maximumFractionDigits: 0 })
	fromTheWebApp := map[int64]string{
		0:       "BDT 0",
		1:       "BDT 1",
		999:     "BDT 999",
		1000:    "BDT 1,000",
		5000:    "BDT 5,000",
		100000:  "BDT 100,000",
		1234567: "BDT 1,234,567",
	}
	for amount, want := range fromTheWebApp {
		if got := Money(amount); got != want {
			t.Errorf("Money(%d) = %q, but the dashboard shows %q for the same figure", amount, got, want)
		}
	}
}

