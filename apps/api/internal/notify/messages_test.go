// builderCase is one notification type. `amount` is the figure the message is
// required to state; leave it at -1 for the builders that carry no money.
type builderCase struct {
	// builder is the exported function name in messages.go. The census matches
	// on this, so it must be spelled exactly.
	builder string
	// invoke renders the message for a given amount. Builders with no money
	// ignore the argument.
	invoke func(amount int64) (title, message string)
	// carriesMoney is false for the staff task feed and the registration
	// notices, which state no figure by design.
	carriesMoney bool
	// wantTitle is the exact title. A title is a fixed string in every case —
	// where it varies (loan completion) there is a row per branch.
	wantTitle string
	// mustContain are fragments the message has to keep. They exist so a
	// rewrite that drops the loan number or the bKash reference fails here
	// rather than in a member's inbox.
	mustContain []string
}

