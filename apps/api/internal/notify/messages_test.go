// Amounts every money-carrying builder is rendered at. 0 and the int64 ceiling
// are here because WO-52 asks for both boundaries: 0 is what a corrected
// posting can legitimately be, and the ceiling is where a float64 would already
// have lost the low digits.
var moneyAmounts = []int64{0, 1, 999, 1000, 50000, 1234567, 9223372036854775807}

// A decimal point in a money message means a float crept back in. There is no
// sub-taka unit, so no message has any business printing one.
var anyDecimal = regexp.MustCompile(`\d[.,]\d{1,2}\b`)

// Digit runs, so the test can prove no *other* number in the body could be read
// as the amount.
var digitRun = regexp.MustCompile(`[0-9][0-9,]*`)

func TestBuilderMessages(t *testing.T) {
	for _, c := range builderCases() {
		if !c.carriesMoney {
			title, message := c.invoke(0)
			checkCommon(t, c, title, message)
			continue
		}
		for _, amount := range moneyAmounts {
			title, message := c.invoke(amount)
			checkCommon(t, c, title, message)
			checkMoneyMessage(t, c, amount, message)
		}
	}
}

func checkCommon(t *testing.T, c builderCase, title, message string) {
	t.Helper()
	if title != c.wantTitle {
		t.Errorf("%s title = %q, want %q", c.builder, title, c.wantTitle)
	}
	if strings.TrimSpace(message) == "" {
		t.Fatalf("%s produced an empty message", c.builder)
	}
	if !strings.HasSuffix(strings.TrimSpace(message), ".") {
		t.Errorf("%s message does not end in a full stop: %q", c.builder, message)
	}
	for _, fragment := range c.mustContain {
		if !strings.Contains(message, fragment) {
			t.Errorf("%s message %q is missing %q", c.builder, message, fragment)
		}
	}
	// %!s(MISSING), %!d(int64=...) — a Sprintf whose arguments stopped matching
	// its verbs. It renders to the member rather than failing at the call site.
	if strings.Contains(message, "%!") || strings.Contains(message, "%s") || strings.Contains(message, "%d") {
		t.Errorf("%s message has an unrendered format verb: %q", c.builder, message)
	}
}

func checkMoneyMessage(t *testing.T, c builderCase, amount int64, message string) {
	t.Helper()

	want := Money(amount)

	// 1. The amount appears exactly once, as whole taka, equal to the int64
	//    passed in. Twice is as wrong as never: a member reading two figures has
	//    to guess which one left their account.
	if n := strings.Count(message, want); n != 1 {
		t.Errorf("%s(%d): %q contains %q %d times, want exactly 1", c.builder, amount, message, want, n)
	}

	// 2. No decimal point anywhere. This is the LEDGER-07 regression test: put
	//    `%.2f` back in messages.go and every row here goes red.
	if anyDecimal.MatchString(message) {
		t.Errorf("%s(%d): %q prints a fractional amount — money is whole taka (rule 1)",
			c.builder, amount, message)
	}

	// 3. No other number in the body can be mistaken for the amount. Digit runs
	//    that belong to a loan number or a reference are excluded by removing
	//    those known fragments first.
	stripped := strings.Replace(message, want, "", 1)
	for _, fragment := range c.mustContain {
		stripped = strings.ReplaceAll(stripped, fragment, "")
	}
	for _, other := range digitRun.FindAllString(stripped, -1) {
		if other == FormatTaka(amount) {
			t.Errorf("%s(%d): %q repeats the figure outside the %q it states",
				c.builder, amount, message, want)
		}
	}

	// 4. The unit is always stated. "50,000" alone is not an amount of anything.
	if !strings.Contains(message, CurrencyCode) {
		t.Errorf("%s(%d): %q states a figure with no currency code", c.builder, amount, message)
	}
}

