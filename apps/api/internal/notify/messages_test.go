// notTheseBuilders are exported functions in messages.go that are helpers, not
// notification types, and so have their own tests rather than a table row.
var notTheseBuilders = map[string]bool{
	"FormatTaka": true, // TestFormatTaka
	"Money":      true, // TestFormatTakaMatchesTheWebApp
}

// TestEveryBuilderIsTested reads messages.go and fails when an exported builder
// has no row in builderCases().
//
// **This test is supposed to fail when you add a notification.** Add the table
// row; do not add the name to notTheseBuilders unless the function genuinely is
// not a notification type. The balance writers have the same census
// (TestBalanceWritersAreEnumerated) and it is what caught LEDGER-05.
func TestEveryBuilderIsTested(t *testing.T) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "messages.go", nil, 0)
	if err != nil {
		t.Fatalf("parse messages.go: %v", err)
	}

	tested := map[string]bool{}
	for _, c := range builderCases() {
		tested[c.builder] = true
	}

	var untested []string
	var found int
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || !fn.Name.IsExported() {
			continue
		}
		// A builder is an exported func returning exactly (string, string).
		results := fn.Type.Results
		if results == nil || len(results.List) != 2 {
			continue
		}
		isString := func(f *ast.Field) bool {
			ident, ok := f.Type.(*ast.Ident)
			return ok && ident.Name == "string"
		}
		if !isString(results.List[0]) || !isString(results.List[1]) {
			continue
		}
		name := fn.Name.Name
		if notTheseBuilders[name] {
			continue
		}
		found++
		if !tested[name] {
			untested = append(untested, name)
		}
	}

	if found == 0 {
		t.Fatal("the census found no builders at all — it has stopped reading messages.go")
	}
	if len(untested) > 0 {
		t.Errorf("these notification builders have no row in builderCases(): %s\n"+
			"Add one. Every string here is read by a member.", strings.Join(untested, ", "))
	}

	// And the reverse: a table row naming a builder that no longer exists is a
	// test asserting nothing.
	declared := map[string]bool{}
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv == nil {
			declared[fn.Name.Name] = true
		}
	}
	for name := range tested {
		if !declared[name] {
			t.Errorf("builderCases() has a row for %q, which is not declared in messages.go", name)
		}
	}
}

// TestNoFloatInMessages is the blunt instrument behind checkMoneyMessage: it
// reads the source. A future builder that uses a float64 for an amount would
// pass every string assertion above at the sample values and still lose
// precision at scale, so the type is banned outright rather than tested around.
func TestNoFloatInMessages(t *testing.T) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "messages.go", nil, parser.ParseComments)
	if err != nil {
		t.Fatalf("parse messages.go: %v", err)
	}
	ast.Inspect(file, func(n ast.Node) bool {
		ident, ok := n.(*ast.Ident)
		if !ok {
			return true
		}
		if ident.Name == "float64" || ident.Name == "float32" {
			t.Errorf("%s: messages.go uses %s — amounts are int64 whole taka (rule 1)",
				fset.Position(ident.Pos()), ident.Name)
		}
		return true
	})
}
